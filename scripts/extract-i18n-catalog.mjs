import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const roots = ["src/app", "src/components"];
const translatableAttributes = new Set([
  "aria-label",
  "placeholder",
  "title",
  "alt"
]);
const translatableProperties = new Set([
  "label",
  "title",
  "copy",
  "description",
  "message",
  "subtitle",
  "helper",
  "empty",
  "fallback"
]);
const phrases = new Set();

function decodeEntities(value) {
  return value
    .replaceAll("&apos;", "'")
    .replaceAll("&quot;", '"')
    .replaceAll("&amp;", "&")
    .replaceAll("&nbsp;", " ");
}

function normalize(value) {
  return decodeEntities(value).replace(/\s+/g, " ").trim();
}

function add(value) {
  const normalized = normalize(value);

  if (
    normalized.length >= 2 &&
    normalized.length <= 800 &&
    /[A-Za-z]/.test(normalized) &&
    !normalized.startsWith("http") &&
    !normalized.startsWith("/") &&
    !/^(?:mailto|tel):/.test(normalized) &&
    !/(?:^|\s)(?:sm:|md:|lg:|xl:|2xl:|h-|w-|mt-|mb-|ml-|mr-|mx-|my-|pt-|pb-|pl-|pr-|px-|py-|text-|bg-|border-|grid|flex|absolute|relative|cursor-|hover:|focus:|disabled:|aria-)/.test(
      normalized
    ) &&
    !/^[\w-]+-\{value\}/.test(normalized)
  ) {
    phrases.add(normalized);
  }
}

function propertyName(node) {
  if (ts.isIdentifier(node) || ts.isStringLiteral(node)) return node.text;
  return "";
}

function templateText(node) {
  const pieces = [node.head.text];

  for (const span of node.templateSpans) {
    pieces.push("{value}", span.literal.text);
  }

  return pieces.join("");
}

function visit(node) {
  if (ts.isJsxText(node)) add(node.getText());

  if (ts.isJsxAttribute(node)) {
    const name = node.name.getText();

    if (translatableAttributes.has(name) && node.initializer) {
      if (ts.isStringLiteral(node.initializer)) add(node.initializer.text);
      if (
        ts.isJsxExpression(node.initializer) &&
        node.initializer.expression &&
        (ts.isStringLiteral(node.initializer.expression) ||
          ts.isNoSubstitutionTemplateLiteral(node.initializer.expression))
      ) {
        add(node.initializer.expression.text);
      }
    }
  }

  if (
    ts.isPropertyAssignment(node) &&
    translatableProperties.has(propertyName(node.name))
  ) {
    if (ts.isStringLiteralLike(node.initializer)) add(node.initializer.text);
    if (ts.isTemplateExpression(node.initializer)) add(templateText(node.initializer));
  }

  if (ts.isJsxExpression(node) && node.expression) {
    if (ts.isStringLiteralLike(node.expression)) add(node.expression.text);
    if (ts.isTemplateExpression(node.expression)) add(templateText(node.expression));
  }

  if (ts.isCallExpression(node)) {
    const callee = node.expression.getText();

    if (/^(?:setError|setLiveMessage|fail|errorMessage)$/.test(callee)) {
      for (const argument of node.arguments) {
        if (ts.isStringLiteralLike(argument)) add(argument.text);
        if (ts.isTemplateExpression(argument)) add(templateText(argument));
      }
    }
  }

  ts.forEachChild(node, visit);
}

function sourceFiles(root) {
  const files = [];

  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const fullPath = path.join(root, entry.name);

    if (entry.isDirectory()) {
      if (fullPath.replaceAll("\\", "/").includes("/app/api/")) continue;
      files.push(...sourceFiles(fullPath));
    } else if (/\.(?:ts|tsx)$/.test(entry.name)) {
      files.push(fullPath);
    }
  }

  return files;
}

for (const root of roots) {
  for (const file of sourceFiles(root)) {
    const source = fs.readFileSync(file, "utf8");
    const sourceFile = ts.createSourceFile(
      file,
      source,
      ts.ScriptTarget.Latest,
      true,
      file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS
    );
    visit(sourceFile);
  }
}

const instantTranslationFile = "src/i18n/instant-translations.ts";
const instantTranslationSource = ts.createSourceFile(
  instantTranslationFile,
  fs.readFileSync(instantTranslationFile, "utf8"),
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TS
);

function visitInstantTranslations(node) {
  if (ts.isPropertyAssignment(node) && ts.isStringLiteralLike(node.initializer)) {
    add(propertyName(node.name));
  }

  ts.forEachChild(node, visitInstantTranslations);
}

visitInstantTranslations(instantTranslationSource);

const catalog = [...phrases].sort();

if (process.argv.includes("--write")) {
  const target = "src/i18n/source-catalog.generated.ts";
  const output = `// Generated by scripts/extract-i18n-catalog.mjs.\n// Re-run npm run i18n:extract after adding or changing interface copy.\n\nexport const sourceCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`;
  fs.writeFileSync(target, output, "utf8");
  process.stdout.write(`Wrote ${catalog.length} source phrases to ${target}\n`);
} else {
  process.stdout.write(`${JSON.stringify(catalog, null, 2)}\n`);
}
